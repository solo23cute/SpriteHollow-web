const SPECIES_FAMILY_BY_ID = new Map();
SPECIES_FAMILY_GROUPS.forEach((family) => {
  SPECIES_FAMILY_BY_ID.set(family.id, family);
  family.species.forEach((species) => SPECIES_FAMILY_BY_SPECIES.set(species, family));
});

/** Return the explicit family record for a species, or null if it is unknown. */
function speciesFamilyFor(species) {
  return SPECIES_FAMILY_BY_SPECIES.get(species) || null;
}

/** Return the display label for a family id. */
function speciesFamilyLabel(familyId) {
  return SPECIES_FAMILY_BY_ID.get(familyId)?.label || '';
}

